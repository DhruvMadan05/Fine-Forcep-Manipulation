#!/usr/bin/env python3
"""PSM kinematics calibrated against the AMBF simulator.

Model
-----
Product of exponentials (PoE) in the PSM *base link* frame:

    T_base_gripper(q) = exp([S1] q1) ... exp([S6] q6) M

with q = (yaw, pitch, insertion, roll, wrist pitch, jaw) and closed jaws
(gripper1 = jaw, gripper2 = -jaw). Each screw S_i is measured from the
simulator by moving joint i on its own (collect_psm_samples.py), so the
model captures the *effective* kinematics of the parallelogram (pitch is a
rotation about an axis through the RCM) rather than the physical linkage.

The jaw tip is the gripper-link point at +y * jaw_length (jaw pointing axis
is the gripper link's +y, measured in sim), and jaw_length comes from the
gripper mesh.

Run directly to (re)fit from data/psm_fk_samples.json, validate on the
held-out random samples, and write config/psm_kinematics.yaml:

    python3 scripts/reachability/psm_kinematics.py
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import yaml
from scipy.spatial.transform import Rotation

sys.path.insert(0, str(Path(__file__).resolve().parent))
from stl_mesh import TriMesh  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SAMPLES = REPO_ROOT / "data" / "psm_fk_samples.json"
DEFAULT_MODEL = REPO_ROOT / "config" / "psm_kinematics.yaml"
JOINT_LABELS = ["yaw", "pitch", "insertion", "roll", "wrist_pitch", "jaw"]
EE_LINK = "toolgripper1link"


# ----------------------------------------------------------------------------
# SE(3) helpers (batched over leading dims)
# ----------------------------------------------------------------------------
def skew(w):
    w = np.asarray(w)
    z = np.zeros(w.shape[:-1])
    return np.stack([np.stack([z, -w[..., 2], w[..., 1]], -1),
                     np.stack([w[..., 2], z, -w[..., 0]], -1),
                     np.stack([-w[..., 1], w[..., 0], z], -1)], -2)


def exp_screw(S, theta):
    """S: (6,) screw [w, v]; theta: (...,). Returns (..., 4, 4)."""
    theta = np.asarray(theta, dtype=float)
    w, v = S[:3], S[3:]
    T = np.zeros(theta.shape + (4, 4))
    T[..., 3, 3] = 1.0
    if np.linalg.norm(w) < 1e-9:          # prismatic
        T[..., :3, :3] = np.eye(3)
        T[..., :3, 3] = theta[..., None] * v
        return T
    W = skew(w)
    W2 = W @ W
    s, c = np.sin(theta)[..., None, None], np.cos(theta)[..., None, None]
    R = np.eye(3) + s * W + (1 - c) * W2
    G = np.eye(3) * theta[..., None, None] + (1 - c) * W + (theta[..., None, None] - s) * W2
    T[..., :3, :3] = R
    T[..., :3, 3] = G @ v
    return T


def adjoint(T):
    R, p = T[..., :3, :3], T[..., :3, 3]
    A = np.zeros(T.shape[:-2] + (6, 6))
    A[..., :3, :3] = R
    A[..., 3:, 3:] = R
    A[..., 3:, :3] = skew(p) @ R
    return A


def pose_to_T(pose):
    T = np.eye(4)
    T[:3, :3] = Rotation.from_quat(pose["quat_xyzw"]).as_matrix()
    T[:3, 3] = pose["pos"]
    return T


def rpy_to_R(r, p, y):
    """AMBF 'orientation: {r, p, y}' = fixed-axis XYZ roll-pitch-yaw."""
    return Rotation.from_euler("xyz", [r, p, y]).as_matrix()


# ----------------------------------------------------------------------------
# Model
# ----------------------------------------------------------------------------
class PSMKinematics:
    def __init__(self, screws, M, jaw_length, limits, rcm):
        self.S = np.asarray(screws, dtype=float)       # (6, 6) in base frame
        self.M = np.asarray(M, dtype=float)            # (4, 4) in base frame
        self.jaw_length = float(jaw_length)
        self.limits = np.asarray(limits, dtype=float)  # (6, 2)
        self.rcm = np.asarray(rcm, dtype=float)        # (3,) in base frame

    # ---- persistence -------------------------------------------------------
    @classmethod
    def load(cls, path=DEFAULT_MODEL):
        d = yaml.safe_load(Path(path).read_text())
        return cls([d["screws"][k] for k in JOINT_LABELS], d["M"], d["jaw_length"],
                   [d["limits"][k] for k in JOINT_LABELS], d["rcm_in_base"])

    def save(self, path, extra=None):
        d = {"_comment": "Generated by scripts/reachability/psm_kinematics.py from "
                         "data/psm_fk_samples.json. PoE model in the PSM base-link frame; "
                         "q = (yaw, pitch, insertion, roll, wrist_pitch, jaw), closed jaws.",
             "screws": {k: self.S[i].round(8).tolist() for i, k in enumerate(JOINT_LABELS)},
             "M": self.M.round(8).tolist(),
             "jaw_length": round(self.jaw_length, 6),
             "limits": {k: self.limits[i].tolist() for i, k in enumerate(JOINT_LABELS)},
             "rcm_in_base": self.rcm.round(6).tolist()}
        if extra:
            d.update(extra)
        Path(path).write_text(yaml.safe_dump(d, sort_keys=False, default_flow_style=None))

    # ---- forward kinematics -----------------------------------------------
    def fk_all(self, q):
        """q: (..., 6). Returns list of cumulative products P_i = e^S1q1..e^Siqi
        (each (..., 4, 4)) and T = P_6 M."""
        q = np.asarray(q, dtype=float)
        P = np.broadcast_to(np.eye(4), q.shape[:-1] + (4, 4)).copy()
        prods = []
        for i in range(6):
            P = P @ exp_screw(self.S[i], q[..., i])
            prods.append(P)
        return prods, P @ self.M

    def fk(self, q):
        return self.fk_all(q)[1]

    def tip_and_axis(self, q):
        """Jaw tip position and jaw pointing axis, both (..., 3), base frame."""
        T = self.fk(q)
        axis = T[..., :3, 1]
        return T[..., :3, 3] + self.jaw_length * axis, axis

    def shaft_points(self, q):
        """RCM, wrist-pitch point (end of shaft) and jaw tip, base frame.
        The wrist point is where the shaft ends: RCM + (insertion offset) * dir,
        computed from the roll screw's axis (shaft axis)."""
        prods, T = self.fk_all(q)
        tip = T[..., :3, 3] + self.jaw_length * T[..., :3, 1]
        # wrist pitch axis point, transformed by joints 1..4 (it's on the
        # wrist-pitch screw axis; precomputed point in zero config)
        wp = (prods[3] @ np.append(self._wrist_point0, 1.0))[..., :3]
        return np.broadcast_to(self.rcm, wp.shape), wp, tip

    @property
    def _wrist_point0(self):
        if not hasattr(self, "_wp0"):
            w, v = self.S[4, :3], self.S[4, 3:]
            # point on the axis closest to the gripper origin at zero config
            r0 = np.cross(w, v) / np.dot(w, w)
            g = self.M[:3, 3]
            self._wp0 = r0 + np.dot(g - r0, w) * w / np.dot(w, w)
        return self._wp0

    def space_jacobian(self, q):
        prods, T = self.fk_all(q)
        J = np.empty(np.shape(q)[:-1] + (6, 6))
        J[..., :, 0] = self.S[0]
        for i in range(1, 6):
            J[..., :, i] = np.einsum("...ij,j->...i", adjoint(prods[i - 1]), self.S[i])
        return J, T

    # ---- inverse kinematics -----------------------------------------------
    def ik(self, tip, approach, cone_deg=20.0, iters=60, seeds=None, damping=1e-4):
        """Batched IK for jaw-tip position + jaw axis within a cone.

        tip, approach: (N, 3) in base frame (approach = desired jaw axis).
        The jaw axis only has to lie within cone_deg of approach; at each
        iteration the target axis is the point of the cone closest to the
        current jaw axis (so the solver uses the slack to reduce wrist bend).
        Roll about the jaw axis is free. Joint limits enforced by projection.

        Returns dict with q (N, 6), pos_err (N,), ang_err (N,) [deg beyond
        cone], best over the seeds.
        """
        tip = np.atleast_2d(tip).astype(float)
        a = np.atleast_2d(approach).astype(float)
        a = a / np.linalg.norm(a, axis=1, keepdims=True)
        cone = np.deg2rad(cone_deg)
        lo, hi = self.limits[:, 0], self.limits[:, 1]
        if seeds is None:
            seeds = [0.0, np.pi / 2, -np.pi / 2, np.pi * 0.95]   # roll seeds
        best = None
        for roll0 in seeds:
            q = self._initial_guess(tip, a, roll0)
            for _ in range(iters):
                J, T = self.space_jacobian(q)
                R, p = T[:, :3, :3], T[:, :3, 3]
                axis = R[:, :, 1]
                cur_tip = p + self.jaw_length * axis
                tgt_axis = _project_into_cone(axis, a, cone)
                # orientation error: rotate axis onto tgt_axis (2-DOF, roll free)
                w_err = np.cross(axis, tgt_axis)
                # space-frame twist relating tip velocity: v_tip = v_s + w x tip
                pos_err = tip - cur_tip
                # Task Jacobian rows for [w (3), v_tip (3)]:
                # v_tip = v_s + w x p_tip  ->  Jv_tip = Jv_s - [p_tip]x Jw
                Jw = J[:, :3, :]
                Jv = J[:, 3:, :] - skew(cur_tip) @ Jw
                # remove the roll-about-jaw-axis component from orientation rows
                Pa = np.eye(3) - axis[:, :, None] * axis[:, None, :]
                Jt = np.concatenate([Pa @ Jw, Jv], axis=1)          # (N, 6, 6)
                e = np.concatenate([w_err, pos_err], axis=1)        # (N, 6)
                # scale: 1 rad ~ 10 mm
                Wt = np.array([0.01, 0.01, 0.01, 1, 1, 1])
                Jt = Jt * Wt[None, :, None]
                e = e * Wt[None]
                JtT = Jt.transpose(0, 2, 1)
                H = JtT @ Jt + damping * np.eye(6)
                dq = np.linalg.solve(H, (JtT @ e[..., None]))[..., 0]
                dq = np.clip(dq, -0.3, 0.3)
                dq[:, 2] = np.clip(dq[:, 2], -0.03, 0.03)
                q = np.clip(q + dq, lo, hi)
            res = self._residuals(q, tip, a, cone)
            if best is None:
                best = res
            else:
                better = _score(res) < _score(best)
                for k in best:
                    best[k] = np.where(better[(...,) + (None,) * (best[k].ndim - 1)], res[k], best[k])
        return best

    def _residuals(self, q, tip, a, cone):
        cur_tip, axis = self.tip_and_axis(q)
        ang = np.arccos(np.clip(np.einsum("ij,ij->i", axis, a), -1, 1))
        return {"q": q, "pos_err": np.linalg.norm(cur_tip - tip, axis=1),
                "ang_err": np.rad2deg(np.maximum(0.0, ang - cone))}

    def _initial_guess(self, tip, a, roll0):
        """Point the shaft from the RCM at the wrist point estimate, wrist
        straight, by a tiny 3-DOF solve over (yaw, pitch, insertion)."""
        q = np.zeros((len(tip), 6))
        q[:, 3] = roll0
        wrist_target = tip - (self.jaw_length + 0.009) * a
        q[:, 2] = np.clip(np.linalg.norm(wrist_target - self.rcm, axis=1), *self.limits[2])
        for _ in range(15):
            J, T = self.space_jacobian(q)
            _, wp, _ = self.shaft_points(q)
            e = wrist_target - wp
            Jv = (J[:, 3:, :3] - skew(wp) @ J[:, :3, :3])
            H = Jv.transpose(0, 2, 1) @ Jv + 1e-6 * np.eye(3)
            d = np.linalg.solve(H, (Jv.transpose(0, 2, 1) @ e[..., None]))[..., 0]
            q[:, :3] = np.clip(q[:, :3] + np.clip(d, -0.3, 0.3), self.limits[:3, 0], self.limits[:3, 1])
        return q


def _project_into_cone(axis, a, cone):
    """Closest unit vector to `axis` within `cone` of `a` (rows)."""
    c = np.clip(np.einsum("ij,ij->i", axis, a), -1, 1)
    ang = np.arccos(c)
    inside = ang <= cone
    perp = axis - c[:, None] * a
    n = np.linalg.norm(perp, axis=1, keepdims=True)
    perp = np.where(n > 1e-9, perp / np.maximum(n, 1e-12), _any_perp(a))
    edge = np.cos(cone) * a + np.sin(cone) * perp
    return np.where(inside[:, None], axis, edge)


def _any_perp(a):
    t = np.where(np.abs(a[:, :1]) < 0.9, np.array([[1.0, 0, 0]]), np.array([[0, 1.0, 0]]))
    p = np.cross(a, t)
    return p / np.linalg.norm(p, axis=1, keepdims=True)


def _score(res):
    return res["pos_err"] * 1000.0 + res["ang_err"]   # mm + deg


# ----------------------------------------------------------------------------
# Calibration from sim samples
# ----------------------------------------------------------------------------
def log_rigid(T):
    """Screw (w*theta, v*theta) of a rigid motion T (4x4)."""
    R, p = T[:3, :3], T[:3, 3]
    rv = Rotation.from_matrix(R).as_rotvec()
    th = np.linalg.norm(rv)
    if th < 1e-7:
        return np.r_[np.zeros(3), p]
    w = rv / th
    W = skew(w)
    Ginv = np.eye(3) / th - W / 2 + (1 / th - 0.5 / np.tan(th / 2)) * (W @ W)
    return np.r_[w * th, (Ginv @ p) * th]


def fit_from_samples(samples_doc, adf_path):
    samples = samples_doc["samples"]
    T_wb = pose_to_T(samples[0]["poses"]["baselink"])
    T_bw = np.linalg.inv(T_wb)
    ee = lambda s: T_bw @ pose_to_T(s["poses"][EE_LINK])  # noqa: E731
    cal = [s for s in samples if s["kind"] == "calibration"]
    zero = cal[0]
    M = ee(zero)
    Minv = np.linalg.inv(M)
    screws = []
    for i in range(6):
        ests = []
        for s in cal[1:]:
            q = np.asarray(s["q_meas"])
            others = np.delete(q, i)
            if abs(q[i]) < 1e-3 or np.max(np.abs(others)) > 5e-3:
                continue
            xi = log_rigid(ee(s) @ Minv) / q[i]
            ests.append(xi)
        if not ests:
            sys.exit(f"ERROR: no calibration samples for joint {JOINT_LABELS[i]}")
        S = np.mean(ests, axis=0)
        if i == 2:                      # prismatic: unit translation, no rotation
            S[:3] = 0.0
            S[3:] /= np.linalg.norm(S[3:])
        else:                           # revolute: unit axis, no pitch
            w = S[:3] / np.linalg.norm(S[:3])
            # point on axis from v = -w x r  =>  r = w x v (for unit w)
            r = np.cross(w, S[3:] / np.linalg.norm(S[:3]))
            S = np.r_[w, -np.cross(w, r)]
        screws.append(S)
    screws = np.array(screws)

    # RCM = closest point between the yaw and pitch axes
    def axis_line(S):
        w, v = S[:3], S[3:]
        return np.cross(w, v), w
    (p1, d1), (p2, d2) = axis_line(screws[0]), axis_line(screws[1])
    A = np.array([[d1 @ d1, -d1 @ d2], [d1 @ d2, -d2 @ d2]])
    t = np.linalg.solve(A, [(p2 - p1) @ d1, (p2 - p1) @ d2])
    c1, c2 = p1 + t[0] * d1, p2 + t[1] * d2
    rcm, axis_gap = (c1 + c2) / 2, np.linalg.norm(c1 - c2)

    # jaw length from the gripper mesh (+y extent) and joint limits from the ADF
    adf = yaml.safe_load(Path(adf_path).read_text())
    body = adf["BODY tool gripper1 link"]
    mesh = TriMesh.from_stl(Path(adf_path).parent / adf["high resolution path"] / body["mesh"],
                            body.get("scale", 1.0))
    jaw_length = mesh.bounds[1][1]
    jl = {
        "yaw": "JOINT base link-yaw link",
        "pitch": "JOINT yaw link-pitch back link",
        "insertion": "JOINT pitch end link-main insertion link",
        "roll": "JOINT main insertion link-tool roll link",
        "wrist_pitch": "JOINT tool roll link-tool pitch link",
        "jaw": "JOINT tool pitch link-tool gripper1 link",
    }
    limits = [[adf[jl[k]]["joint limits"]["low"], adf[jl[k]]["joint limits"]["high"]]
              for k in JOINT_LABELS]
    model = PSMKinematics(screws, M, jaw_length, limits, rcm)
    return model, {"axis_gap_yaw_pitch_m": float(axis_gap),
                   "calibrated_base_pose_world": T_wb.round(6).tolist()}


def validate(model, samples_doc):
    samples = samples_doc["samples"]
    T_bw = np.linalg.inv(pose_to_T(samples[0]["poses"]["baselink"]))
    rnd = [s for s in samples if s["kind"] == "random"]
    q = np.array([s["q_meas"] for s in rnd])
    T_meas = np.array([T_bw @ pose_to_T(s["poses"][EE_LINK]) for s in rnd])
    T_pred = model.fk(q)
    pos = np.linalg.norm(T_pred[:, :3, 3] - T_meas[:, :3, 3], axis=1) * 1000
    Rerr = np.einsum("nji,njk->nik", T_pred[:, :3, :3], T_meas[:, :3, :3])
    ang = np.rad2deg(np.linalg.norm(Rotation.from_matrix(Rerr).as_rotvec(), axis=1))
    return {"n": len(rnd), "pos_err_mm_mean": float(pos.mean()), "pos_err_mm_max": float(pos.max()),
            "rot_err_deg_mean": float(ang.mean()), "rot_err_deg_max": float(ang.max())}


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--samples", default=str(DEFAULT_SAMPLES))
    ap.add_argument("--adf", default=str(REPO_ROOT / "adf" / "generated" / "psm1.yaml"),
                    help="Generated PSM ADF (for joint limits and the gripper mesh)")
    ap.add_argument("--out", default=str(DEFAULT_MODEL))
    args = ap.parse_args()

    doc = json.loads(Path(args.samples).read_text())
    model, info = fit_from_samples(doc, args.adf)
    val = validate(model, doc)
    print(f"RCM in base frame: {model.rcm.round(5)}  (yaw/pitch axis gap "
          f"{info['axis_gap_yaw_pitch_m'] * 1000:.3f} mm)")
    print(f"jaw length: {model.jaw_length * 1000:.2f} mm")
    print(f"FK validation on {val['n']} held-out random samples: "
          f"pos err mean {val['pos_err_mm_mean']:.3f} mm / max {val['pos_err_mm_max']:.3f} mm, "
          f"rot err mean {val['rot_err_deg_mean']:.3f} deg / max {val['rot_err_deg_max']:.3f} deg")
    model.save(args.out, {"fit_info": info, "fk_validation": val})
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
